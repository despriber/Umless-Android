/** 后端文字（错误信息、任务进度、键盘状态提示），跟随 [Umless.language]。键名与桌面端 i18n.py 一致，可增补 Android 专用的键 */
object I18n {
    private val PLACEHOLDER = Regex("""\{(\w+)\}""")

    /** 取当前语言的文字并填入 {name} 占位符；缺失时退回中文，再退回 key 本身 */
    fun t(key: String, vararg args: Pair<String, Any?>): String = tr(currentLanguage(), key, *args)

    /** 指定语言（zh / en）取文字 */
    fun tr(lang: String, key: String, vararg args: Pair<String, Any?>): String {
        val text = (if (lang == "en") EN[key] else ZH[key]) ?: ZH[key] ?: key
        if (args.isEmpty()) return text
        val values = args.associate { (k, v) -> k to format(v) }
        // 与 Python str.format 一样：占位符缺参数时整句不替换
        if (PLACEHOLDER.findAll(text).any { it.groupValues[1] !in values }) {
            UmlessLog.w("I18n", "界面文字占位符不匹配：$key")
            return text
        }
        return PLACEHOLDER.replace(text) { values.getValue(it.groupValues[1]) }
    }

    fun has(key: String) = key in ZH

    /** 两份字典的 key 集合（测试用） */
    internal val zhKeys: Set<String> get() = ZH.keys
    internal val enKeys: Set<String> get() = EN.keys

    private fun currentLanguage(): String = try {
        Umless.language()
    } catch (_: Exception) {
        "zh"
    }

    private fun format(v: Any?): String = when (v) {
        null -> "None"
        is Throwable -> v.message ?: v.javaClass.simpleName
        is Double -> Py.repr(v)
        is Boolean -> if (v) "True" else "False"
        else -> v.toString()
    }

